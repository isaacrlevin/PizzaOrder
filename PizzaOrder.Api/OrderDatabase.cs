using Npgsql;

namespace PizzaOrder;

internal sealed class OrderDatabase : IAsyncDisposable
{
    private readonly NpgsqlDataSource _dataSource;

    public OrderDatabase(string connectionString)
    {
        _dataSource = NpgsqlDataSource.Create(connectionString);
    }

    public async Task InitializeAsync()
    {
        await using var command = _dataSource.CreateCommand();
        command.CommandText = """
                              CREATE TABLE IF NOT EXISTS orders (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  number TEXT NOT NULL UNIQUE,
                                  customer_name TEXT NOT NULL,
                                  customer_key TEXT NOT NULL,
                                  address TEXT NOT NULL,
                                  placed_at TIMESTAMPTZ NOT NULL
                              );
                              CREATE INDEX IF NOT EXISTS ix_orders_customer_key ON orders(customer_key);
                              CREATE TABLE IF NOT EXISTS order_items (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
                                  pizza_name TEXT NOT NULL,
                                  description TEXT NOT NULL,
                                  base_price NUMERIC(10, 2) NOT NULL,
                                  size INTEGER NOT NULL CHECK (size BETWEEN 0 AND 2),
                                  quantity INTEGER NOT NULL CHECK (quantity > 0)
                              );
                              """;
        await command.ExecuteNonQueryAsync();
    }

    public async Task SaveAsync(Order order)
    {
        await using var connection = await _dataSource.OpenConnectionAsync();
        await using var transaction = await connection.BeginTransactionAsync();

        var orderCommand = connection.CreateCommand();
        orderCommand.Transaction = transaction;
        orderCommand.CommandText = """
                                   INSERT INTO orders(number, customer_name, customer_key, address, placed_at)
                                   VALUES ($1, $2, $3, $4, $5)
                                   RETURNING id;
                                   """;
        orderCommand.Parameters.AddWithValue(order.Number);
        orderCommand.Parameters.AddWithValue(order.CustomerName);
        orderCommand.Parameters.AddWithValue(CustomerKey(order.CustomerName));
        orderCommand.Parameters.AddWithValue(order.Address);
        orderCommand.Parameters.AddWithValue(order.PlacedAt.ToUniversalTime());
        var orderId = (long)(await orderCommand.ExecuteScalarAsync() ??
                             throw new InvalidOperationException("Could not save order."));

        foreach (var item in order.Items)
        {
            var itemCommand = connection.CreateCommand();
            itemCommand.Transaction = transaction;
            itemCommand.CommandText = """
                                      INSERT INTO order_items(order_id, pizza_name, description, base_price, size, quantity)
                                      VALUES ($1, $2, $3, $4, $5, $6);
                                      """;
            itemCommand.Parameters.AddWithValue(orderId);
            itemCommand.Parameters.AddWithValue(item.Pizza.Name);
            itemCommand.Parameters.AddWithValue(item.Pizza.Description);
            itemCommand.Parameters.AddWithValue(item.Pizza.BasePrice);
            itemCommand.Parameters.AddWithValue((int)item.Size);
            itemCommand.Parameters.AddWithValue(item.Quantity);
            await itemCommand.ExecuteNonQueryAsync();
        }

        await transaction.CommitAsync();
    }

    public async Task<List<Order>> GetOrdersAsync(string customerName)
    {
        await using var command = _dataSource.CreateCommand();
        command.CommandText = """
                              SELECT o.id, o.number, o.customer_name, o.address, o.placed_at,
                                     i.pizza_name, i.description, i.base_price, i.size, i.quantity
                              FROM orders o
                              JOIN order_items i ON i.order_id = o.id
                              WHERE o.customer_key = $1
                              ORDER BY o.placed_at DESC, i.id;
                              """;
        command.Parameters.AddWithValue(CustomerKey(customerName));

        var orders = new List<Order>();
        var byId = new Dictionary<long, Order>();
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            var id = reader.GetInt64(0);
            if (!byId.TryGetValue(id, out var order))
            {
                order = new Order
                {
                    Number = reader.GetString(1), CustomerName = reader.GetString(2), Address = reader.GetString(3),
                    PlacedAt = new DateTimeOffset(reader.GetDateTime(4), TimeSpan.Zero), Items = []
                };
                byId[id] = order;
                orders.Add(order);
            }

            var pizza = new MenuPizza(reader.GetString(5), reader.GetString(6), reader.GetDecimal(7));
            order.Items.Add(new PizzaItem(pizza, (PizzaSize)reader.GetInt32(8), reader.GetInt32(9)));
        }

        return orders;
    }

    private static string CustomerKey(string name) => name.Trim().ToUpperInvariant();

    public ValueTask DisposeAsync() => _dataSource.DisposeAsync();
}